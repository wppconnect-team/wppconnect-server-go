"""Generate dependency notices from downloaded Go modules and the Go runtime."""
import json
import pathlib
import subprocess

def go(*args):
    return subprocess.check_output(["go", *args], text=True, encoding="utf-8")

raw = go("list", "-deps", "-json", "./cmd/server", "./cmd/token")
decoder = json.JSONDecoder()
modules = {}
while raw.strip():
    package, end = decoder.raw_decode(raw.lstrip())
    raw = raw.lstrip()[end:]
    module = package.get("Module")
    if module and not module.get("Main"):
        module = module.get("Replace", module)
        modules[module["Path"]] = module
parts = ["Third-party Go dependency notices\nGenerated by scripts/dependency-notices.py.\n"
         "Modules and their transitive requirements retain their own licenses.\n"
         "Sources: https://proxy.golang.org/<module>/@v/<version>.zip\n"]
for module in sorted(modules.values(), key=lambda m: m["Path"]):
    directory = pathlib.Path(module["Dir"])
    files = sorted(p for p in directory.iterdir() if p.is_file() and
                   p.name.upper().startswith(("LICENSE", "COPYING", "NOTICE")))
    if not files:
        raise RuntimeError(f"Missing license: {module['Path']}")
    parts.append(f"\n{'=' * 72}\n{module['Path']} {module['Version']}\n")
    for file in files:
        parts.append(f"\n{file.name}\n{file.read_text(encoding='utf-8', errors='replace')}\n")
root = pathlib.Path(go("env", "GOROOT").strip())
parts.append("\nGo runtime\n" + (root / "LICENSE").read_text(encoding="utf-8"))
out = pathlib.Path("third_party/licenses.txt")
out.parent.mkdir(exist_ok=True)
out.write_text("".join(parts).replace("\r\n", "\n"), encoding="utf-8", newline="\n")
